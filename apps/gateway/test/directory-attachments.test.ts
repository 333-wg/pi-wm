import { afterEach, expect, it } from "vitest";
import { mkdtemp, mkdir, writeFile, rm, symlink } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DirectoryAttachments } from "../src/directory-attachments.js";
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(path => rm(path, { recursive: true, force: true }))); });
it("references large live folders without walking/uploading them, persists and exposes actual model reads", async () => {
	const root = await mkdtemp(join(tmpdir(), "directory-reference-")); roots.push(root);
	const folder = join(root, "项目"); await mkdir(folder);
	await Promise.all(Array.from({ length: 2100 }, (_, i) => writeFile(join(folder, `${i}.txt`), `proof ${i}`)));
	await mkdir(join(folder, "empty"));
	const store = new DirectoryAttachments(join(root, "grants"));
	const ref = await store.add("a", folder);
	const resumed = new DirectoryAttachments(join(root, "grants"));
	const tool = resumed.tools("a")[0]!;
	const result = await tool.execute("call", { directoryId: ref.id, action: "read", path: "2099.txt" }, undefined, undefined, {} as Parameters<typeof tool.execute>[4]);
	expect(result.content).toEqual([{ type: "text", text: expect.stringContaining("proof 2099") }]);
	await writeFile(join(folder, "2099.txt"), "changed live");
	expect(await resumed.inspect("a", { directoryId: ref.id, action: "read", path: "2099.txt" })).toMatchObject({ content: "changed live" });
	expect(await resumed.inspect("a", { directoryId: ref.id, action: "glob", pattern: "2099*" })).toMatchObject({ paths: ["2099.txt"] });
	expect(await resumed.inspect("a", { directoryId: ref.id, action: "grep", pattern: "changed", path: "2099.txt" })).toMatchObject({ totalMatches: 1 });
	await expect(resumed.inspect("b", { directoryId: ref.id, action: "list" })).rejects.toThrow("another workspace");
	await expect(resumed.inspect("a", { directoryId: ref.id, action: "read", path: "../grants/x" })).rejects.toThrow();
	await expect(resumed.inspect("a", { directoryId: "../../arbitrary", action: "list" })).rejects.toThrow();
	const outside = join(root, "outside"); await mkdir(outside); await writeFile(join(outside, "secret.txt"), "secret");
	await symlink(outside, join(folder, "escape"), process.platform === "win32" ? "junction" : "dir");
	await expect(resumed.inspect("a", { directoryId: ref.id, action: "read", path: "escape/secret.txt" })).rejects.toThrow("outside workspace");
});
